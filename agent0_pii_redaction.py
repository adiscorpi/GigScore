def _hash(raw: str, prefix: str) -> str:
    """Stable salted SHA-256 pseudonym. Same input → same token always."""
    digest = hashlib.sha256(
        f"{PII_SALT}:{raw.strip().lower()}".encode()
    ).hexdigest()[:12]
    return f"{prefix}_{digest}"


def _resolve_category(narration: str) -> str:
    for pattern, category in NARRATION_KEYWORDS:
        if pattern.search(narration):
            return category
    return "OTHER"


def _parse_amount(s: str) -> float:
    """Converts '6,000.00' or '135.69' to float. Returns 0.0 on failure."""
    try:
        return float(s.replace(",", "").strip())
    except (ValueError, AttributeError):
        return 0.0


def _parse_date(s: str) -> str:
    """Converts DD/MM/YYYY to YYYY-MM-DD. Returns original string on failure."""
    s = (s or "").strip()
    m = re.match(r"(\d{2})/(\d{2})/(\d{4})", s)
    if m:
        return f"{m.group(3)}-{m.group(2)}-{m.group(1)}"
    return s


