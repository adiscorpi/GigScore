# AGENT 0 — COMBINED PDF PARSER + PII GATE
# ─────────────────────────────────────────────────────────────────────────────

class Agent0:
    """
    GigScore Agent 0: PDF Parser + PII Redaction Gate.

    Usage:
        agent0 = Agent0()
        result = agent0.process("path/to/statement.pdf")

        result["transactions"]  → Agent 1
        result["audit_log"]     → Agent 7
    """

    def __init__(self, salt: str = PII_SALT):
        self.salt = salt

    def process(self, pdf_path: str) -> dict:
        """
        Full pipeline:
          1. Parse PDF → raw header + raw transactions
          2. Pseudonymise applicant from account number
          3. Redact all header PII (counts logged, values discarded)
          4. For each transaction:
             a. Extract VPA from narration → hash → NODE_token
             b. Resolve MCC category from narration
             c. Scrub narration of VPA and any residual PII
          5. Build audit log for Agent 7
          6. Return clean output dict
        """
        # ── Step 1: Parse ────────────────────────────────────────────────────
        print(f"  Parsing PDF: {Path(pdf_path).name}")
        header, raw_txns = parse_pdf(pdf_path)
        print(f"  Found {len(raw_txns):,} transactions across all pages")

        # ── Step 2: Pseudonymise applicant ───────────────────────────────────
        raw_account_no  = header.get("account_number", "")
        applicant_token = _hash(raw_account_no or datetime.now(timezone.utc).isoformat(), "APPL")

        # ── Step 3: Count header PII fields (values never stored) ────────────
        pii_fields      = ["name", "account_number", "ifsc", "micr", "phone",
                           "email", "address", "kyc_id", "branch_address"]
        redact_count    = {f: 1 for f in pii_fields if header.get(f)}

        # ── Step 4: Process transactions ─────────────────────────────────────
        vpa_cache: dict[str, str] = {}   # raw_vpa → NODE_token (session only)
        clean_txns: list[dict]    = []

        for txn in raw_txns:
            narration = txn["narration"]

            # 4a. Extract VPA before scrubbing
            vpa_match = VPA_PATTERN.search(narration)
            raw_vpa   = vpa_match.group(0) if vpa_match else ""

            # 4b. Hash VPA → stable NODE token
            if raw_vpa:
                if raw_vpa not in vpa_cache:
                    vpa_cache[raw_vpa] = _hash(raw_vpa, "NODE")
                counterparty_token = vpa_cache[raw_vpa]
            else:
                counterparty_token = "NODE_atm_cash_sentinel"

            # 4c. Resolve category from original (unscubbed) narration
            mcc_category = _resolve_category(narration)

            # 4d. Scrub VPA from narration
            narration_clean = VPA_PATTERN.sub("[VPA]", narration).strip()

            clean_txns.append({
                "date":               txn["date"],
                "amount":             txn["amount"],
                "direction":          txn["direction"],
                "narration_clean":    narration_clean,
                "mcc_category":       mcc_category,
                "running_balance":    txn["running_balance"],
                "counterparty_token": counterparty_token,
            })

        # ── Step 5: Audit log ────────────────────────────────────────────────
        audit_log = {
            "applicant_token":          applicant_token,
            "redacted_field_counts":    redact_count,
            "vpa_tokens_created":       len(vpa_cache),
            "total_transactions":       len(clean_txns),
            "processing_timestamp":     datetime.now(timezone.utc).isoformat(),
            "dpdp_compliant":           True,
            "fields_passed_downstream": [
                "date", "amount", "direction", "narration_clean",
                "mcc_category", "running_balance", "counterparty_token"
            ],
            "fields_redacted":          pii_fields,
            "pseudonymisation_method":  "SHA-256 salted, 12-char hex token",
            "note": (
                "Counterparty VPAs hashed to stable NODE tokens. "
                "MCC category labels preserved for Agent 3 Social Trust Graph. "
                "No raw PII values stored in this log."
            ),
        }

        return {
            "applicant_token": applicant_token,
            "transactions":    clean_txns,
            "audit_log":       audit_log,
        }


