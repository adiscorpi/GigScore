# Fields we extract from the header tables
HEADER_FIELD_MAP = {
    "customer id":       "customer_id",
    "account id":        "account_number",
    "statement period":  "statement_period",
    "customer name":     "name",
    "address":           "address",
    "email":             "email",
    "phone":             "phone",
    "pan":               "kyc_id",
    "aadhaar":           "kyc_id",
    "branch":            "branch",
    "branch address":    "branch_address",
    "ifsc":              "ifsc",
    "micr":              "micr",
    "account opened":    "account_opened",
    "account type":      "account_type",
    "account status":    "account_status",
    "currency":          "currency",
}

# What the transaction table columns look like after pdfplumber extraction
# Note: ₹ renders as 'n' in pdfplumber due to font encoding
TXN_DATE_COL    = 0
TXN_NARR_COL    = 1
TXN_DEBIT_COL   = 2
TXN_CREDIT_COL  = 3
TXN_BALANCE_COL = 4


def _is_txn_header(row: list) -> bool:
    """Detects the transaction table header row."""
    if not row or len(row) < 5:
        return False
    joined = " ".join(str(c or "").lower() for c in row)
    return "date" in joined and "narration" in joined and "balance" in joined


def _is_txn_row(row: list) -> bool:
    """Detects a valid transaction data row (starts with DD/MM/YYYY date)."""
    if not row or len(row) < 5:
        return False
    date_cell = str(row[TXN_DATE_COL] or "").strip()
    return bool(re.match(r"\d{2}/\d{2}/\d{4}", date_cell))


def parse_pdf(pdf_path: str) -> tuple[dict, list[dict]]:
    """
    Parses an IndiaFirst Bank statement PDF.

    Returns:
        header  : dict of raw account holder fields (PII — will be stripped)
        raw_txns: list of raw transaction dicts (narrations unredacted)
    """
    path = Path(pdf_path)
    if not path.exists():
        raise FileNotFoundError(f"PDF not found: {pdf_path}")

    header   = {}
    raw_txns = []

    with pdfplumber.open(str(path)) as pdf:
        for page_num, page in enumerate(pdf.pages):
            tables = page.extract_tables()

            for table in tables:
                if not table:
                    continue

                # ── Header tables (key-value pairs, 2 columns) ───────────────
                if len(table[0]) == 2 and not _is_txn_header(table[0]):
                    for row in table:
                        if not row or len(row) < 2:
                            continue
                        key = str(row[0] or "").strip().lower()
                        val = str(row[1] or "").strip()
                        if key in HEADER_FIELD_MAP and val:
                            field = HEADER_FIELD_MAP[key]
                            header[field] = val

                # ── Transaction table (5 columns) ────────────────────────────
                elif len(table[0]) >= 5:
                    for row in table:
                        if _is_txn_header(row) or not _is_txn_row(row):
                            continue

                        date_str    = str(row[TXN_DATE_COL]    or "").strip()
                        narration   = str(row[TXN_NARR_COL]    or "").strip()
                        debit_str   = str(row[TXN_DEBIT_COL]   or "").strip()
                        credit_str  = str(row[TXN_CREDIT_COL]  or "").strip()
                        balance_str = str(row[TXN_BALANCE_COL] or "").strip()

                        debit  = _parse_amount(debit_str)
                        credit = _parse_amount(credit_str)

                        # Direction: if credit > 0 and debit == 0 → CR, else DR
                        if credit > 0 and debit == 0:
                            direction = "CR"
                            amount    = credit
                        else:
                            direction = "DR"
                            amount    = debit

                        if amount == 0:
                            continue

                        raw_txns.append({
                            "date":            _parse_date(date_str),
                            "amount":          amount,
                            "direction":       direction,
                            "narration":       narration,
                            "running_balance": _parse_amount(balance_str),
                        })

    return header, raw_txns


